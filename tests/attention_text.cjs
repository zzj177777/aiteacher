const fs=require('node:fs'),assert=require('node:assert/strict'),ts=require('typescript');
const React=require('react'),{renderToStaticMarkup}=require('react-dom/server');
const load=require('./load_ts.cjs');
const blocks=load('src/whiteboardBlocks.ts');
const model=load('src/attentionModel.ts',{'./whiteboardBlocks':blocks});
const {attentionSentences:sentences,attentionCues:cues,attentionDelay:delay}=model;
const source=String.raw`**定义**：若存在非零向量 $x$，使`+'\n'+String.raw`$$Ax=\lambda x$$`+'\n则称它为特征向量。\n注意向量不能为零。';
const units=sentences(source);
assert.equal(units.length,2);
assert.ok(units[0].text.includes(String.raw`$$Ax=\lambda x$$`));
assert.ok(units[0].text.endsWith('则称它为特征向量。'));
for(const u of units)assert.equal(source.slice(u.start,u.start+u.text.length),u.text);
const makeMark=(text,quote,id,kind='key_point',style='circle')=>({id,quote,start:text.indexOf(quote),end:text.indexOf(quote)+quote.length,kind,style,explanation:kind==='pitfall'?'别把向量非零和特征值非零混淆。':'',evidence_quote:quote});
assert.deepEqual(cues(units[0],[]),[],'keywords and formulas never create fallback marks');
const first=makeMark(source,'非零向量','first','pitfall','highlight');
assert.equal(cues(units[0],[first])[0].style,'highlight','use the model style even for a condition');
const formula=sentences(String.raw`计算得到 $A^2=I$。`)[0];
const f=makeMark(formula.text,String.raw`$A^2=I$`,'formula','key_point','underline');
assert.equal(cues(formula,[f])[0].quote,String.raw`$A^2=I$`);
assert.deepEqual(cues(formula,[{...f,quote:'wrong'}]),[],'stale text cannot reuse old offsets');
assert.deepEqual(cues(units[1],[first]),[],'do not attach a previous sentence mark to this one');
assert.deepEqual(cues(units[0],[{...first,end:source.length,quote:source.slice(first.start)}]),[],'cross-unit anchors are not silently clipped');
const lists=sentences('先看例子：\n- 第一项\n- 第二项\n最后观察。');
assert.ok(lists.length>=2);
assert.ok(delay('短句')>=2800);assert.ok(delay('长'.repeat(300))<=9000);
const rich=load('src/RichText.tsx');
const component=load('src/AttentionText.tsx',{'./RichText':rich,'./attentionModel':model});
const second=makeMark(source,'不能为零','second','key_point','underline');
const render=(n,marks=[first,second])=>renderToStaticMarkup(React.createElement(component.default,{units,revealed:n,marks}));
assert.equal((render(1,[]).match(/<mark/g)||[]).length,0,'unannotated lecture stays completely unmarked');
const html=render(1);
assert.equal((html.match(/<mark/g)||[]).length,1);
assert.ok(html.includes('attention-row current'));assert.ok(html.includes('attention-row future'));
assert.ok(html.includes('aria-hidden="true"'));
assert.ok(html.includes('class="katex"'));assert.ok(!html.includes('formula-fallback'));
const insights=renderToStaticMarkup(React.createElement(component.AttentionInsights,{cues:[first]}));
assert.ok(insights.includes('可能易错'));assert.ok(insights.includes('教学预测'));
const later=render(2);assert.ok(later.includes('attention-row past'));
assert.equal((later.match(/<mark/g)||[]).length,1);
assert.ok(!later.includes('可能易错'),'past insights do not intrude on a new sentence');
console.log('Attention text verified: model-only exact anchors and styles, empty means unmarked, no regex/first-formula fallback, optional insights and stale/cross-sentence rejection.');
const waiting=renderToStaticMarkup(React.createElement(component.default,{units,revealed:0,marks:[]}));
assert.equal((waiting.match(/attention-row future/g)||[]).length,units.length,'nothing revealed before the first spoken cue');
const reading=renderToStaticMarkup(React.createElement(component.default,{units,revealed:1,marks:[],spokenRange:{first_unit:0,last_unit:0,start:.1,end:1}}));
assert.ok(reading.includes('attention-row current is-reading'));
assert.equal((reading.match(/<mark/g)||[]).length,0,'playback highlighting never fabricates teaching-agent annotations');
