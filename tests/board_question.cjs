const fs=require('node:fs');
const assert=require('node:assert/strict');
const ts=require('typescript');
const compiled=ts.transpileModule(fs.readFileSync('src/boardQuestion.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod={exports:{}};
new Function('module','exports',compiled)(mod,mod.exports);
const {parseChoiceQuestion:parse,choiceAnswer,selectedChoices}=mod.exports;
const actual=String.raw`下列式子中，哪个不是一次函数？A. $y=3x-1$　B. $y=-x$　C. $y=5$　D. $y=\frac{x}{2}+1$`;
const q=parse(actual);
assert.equal(q.options.length,4);
assert.equal(q.options[0].text,'$y=3x-1$');
assert.equal(q.options[3].text,String.raw`$y=\frac{x}{2}+1$`);
assert.equal(q.multiple,false);
assert.equal(q.prompt,'下列式子中，哪个不是一次函数？');
const answer=choiceAnswer(q.options,['C']);
assert.equal(answer,'C. $y=5$');
assert.deepEqual(selectedChoices(q.options,answer),['C']);
assert.deepEqual(selectedChoices(q.options,'C'),['C']);
assert.equal(parse('系数为5，增加多少？'),null);
assert.equal(parse('看看：A. 只有一个'),null);
assert.equal(parse('选择：A. 甲 C. 丙'),null);
assert.equal(parse('公式 $A. x+B. y$ 和代码 `A. one B. two` 是什么意思？'),null);
const protectedQ=parse(String.raw`选一个：A. $\text{B. C.}=1$ B. \(\text{C. D.}=2\) C. `+'`D. no`');
assert.equal(protectedQ.options.length,3);
assert.equal(protectedQ.options[0].text,String.raw`$\text{B. C.}=1$`);
assert.equal(parse('哪个正确？\n**A.** 甲\n**B.** 乙').options[1].text,'乙');
assert.equal(parse('哪个正确？（Ａ）甲 （Ｂ）乙').options[1].id,'B');
assert.equal(parse(String.raw`哪个正确？\nA、甲\nB、乙`).options.length,2);
const multi=parse('多选，选择所有符合的式子：A. $x=1$ B. $x=2$ C. $x=3$');
assert.equal(multi.multiple,true);
assert.deepEqual(selectedChoices(multi.options,choiceAnswer(multi.options,['A','C'])),['A','C']);
const multiline=parse('多选：A. $$a\nb$$ B. $$c\nd$$');
assert.deepEqual(selectedChoices(multiline.options,choiceAnswer(multiline.options,['A','B'])),['A','B']);
console.log('Board choices verified: saved inline questions, formula/code isolation, common labels, single/multiple selection and answer restoration.');
