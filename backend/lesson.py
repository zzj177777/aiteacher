from uuid import uuid4
from .content import DIAGNOSTICS, choose, get_problem
from .math_engine import matrix, number, strings, transform, determinant, triangular, next_hint


def message(state, text, role="teacher", **extra):
    item = {"id": str(uuid4()), "role": role, "text": text, "agent": "student" if role == "student" else "assessment", "kind": "feedback", **extra}
    state["messages"].append(item)
    return item


def new_state():
    state = {"phase": "diagnosis", "revision": 0, "diagnostic_index": 0, "diagnostic_results": [], "matrix": None, "factor": "1", "problem_id": None, "used": [], "attempts": [], "messages": [], "steps": [], "evidence": [], "mistakes": [], "passed": [], "hint_count": 0, "helped": False, "round": 0, "completed": False, "explanation": None}
    message(state, "本节目标是用行变换化上三角形计算三阶行列式。我先安排三个起点诊断，再将明确的教学任务交给授课 Agent；讲解后进入练习和独立测验。", agent="scheduler", kind="announcement")
    return state


def start_problem(state, role):
    problem = choose(role, state["used"])
    if problem is None:
        state["phase"] = "report"
        state["completed"] = False
        message(state, "当前题库的独立题已用完。这次先整理学习记录；结果记为尚未达标，避免重复熟悉题被算成独立掌握。你可以开始新一轮练习。")
        return
    state.update(problem_id=problem["id"], matrix=strings(matrix(problem["matrix"])), factor="1", steps=[], helped=False, hint_count=0, problem_done=False)
    state["used"].append(problem["id"])
    message(state, "已准备好引导练习，接下来安排授课 Agent 讲解方法。" if role == "guided" else "讲解与练习阶段结束，现在交由测评模块检查独立新题。需要提示时本题会转为辅导尝试。", agent="scheduler", kind="handoff", to_agent="lecturer" if role == "guided" else "assessment")


def public_state(state):
    from .lecturer import AGENTS, current_task
    from .teaching_session import projection
    out = {k: v for k, v in state.items() if k not in ("used", "diagnostic_results", "teaching_tasks", "planner")}
    from .planner import public as planner_public
    out["planner"] = planner_public(state)
    # Old persisted messages were unlabelled; never retroactively claim they
    # were generated by an agent.
    out["messages"] = [{"agent": "student" if m["role"] == "student" else "legacy", "kind": "feedback", **m} for m in state["messages"]]
    out["agents"] = AGENTS
    out["teaching_task"] = projection(current_task(state))
    out["paused_teaching_tasks"] = [{"id":t["id"], "title":t["title"], "segment_index":t["session"]["segment_index"], "segment_total":t["session"]["segment_total"]} for t in state.get("teaching_tasks", []) if t.get("status") == "paused" and t.get("session")]
    if state["phase"] == "diagnosis":
        q = DIAGNOSTICS[state["diagnostic_index"]]
        out["diagnostic"] = {k: q[k] for k in ("id", "question", "choices")}
    if state["problem_id"]:
        p = get_problem(state["problem_id"])
        out["problem"] = {"id": p["id"], "title": p["title"], "original": strings(matrix(p["matrix"])), "role": p["role"]}
    out["report"] = make_report(state) if state["phase"] == "report" else None
    if out["report"]:
        from .teaching_session import summaries
        out["report"]["teaching_sessions"] = summaries(state)
        if out["planner"]:
            out["report"]["learning_plan"] = out["planner"]["plan"]
            if not state.get("problem_id"):
                out["report"]["notes"] = ["本次只进行了目标沟通与教学安排，尚未进入实际授课。"]
    return out


def make_report(state):
    return {"passed": state["completed"], "attempts": state["attempts"], "evidence": state["evidence"], "mistakes": state["mistakes"], "diagnostic_score": sum(r["correct"] for r in state["diagnostic_results"]), "explanation": state["explanation"], "notes": ["倍加：Rᵢ ← Rᵢ + kRⱼ，行列式不变。", "交换两行：行列式变号。", "一行乘 k：当前行列式乘 k，恢复原值时需要除以 k。", "上三角形行列式等于主对角线元素的乘积。", "始终保持：原行列式值 = c × 当前行列式值。"], "next": "建议隔 1～3 天用新题独立复习。本次通过并不代表已经验证长期保持。" if state["completed"] else "建议先针对错误复习，再做未见过的题。本次尚未收集到全部独立达标证据。"}


def mistake(state, kind, text):
    state["mistakes"].append({"kind": kind, "text": text, "problem_id": state["problem_id"], "revision": state["revision"] + 1})


def require_problem(state):
    if state["phase"] not in ("guided_practice", "independent_assessment") or state.get("problem_done"):
        raise ValueError("当前不接受这类作答，请继续课堂流程。")


def apply_event(state, kind, payload):
    """Mutate a server-owned state. Caller persists accepted/error attempts atomically."""
    if kind == "planner_message" or (kind == "ask_question" and state["phase"] == "planning"):
        from .planner import handle_message
        return handle_message(state,payload)
    if kind == "confirm_learning_plan":
        from .planner import confirm
        confirm(state,payload)
        return {"plan_confirmed":True}
    if kind == "submit_diagnostic_answer":
        if state["phase"] != "diagnosis":
            raise ValueError("诊断已结束，请刷新课堂。")
        q = DIAGNOSTICS[state["diagnostic_index"]]
        answer = payload.get("choice")
        if type(answer) is not int or answer not in range(len(q["choices"])):
            raise ValueError("请选择一个答案。")
        correct = answer == q["answer"]
        state["diagnostic_results"].append({"concept": q["concept"], "correct": correct})
        message(state, q["choices"][answer], "student")
        message(state, "答对了。" + q["remedy"] if correct else "先补充这条规则：" + q["remedy"])
        if not correct:
            mistake(state, "rule", q["remedy"])
        state["diagnostic_index"] += 1
        if state["diagnostic_index"] == len(DIAGNOSTICS):
            state["phase"] = "guided_practice"
            start_problem(state, "guided")
            from .lecturer import dispatch
            focus = [DIAGNOSTICS[i]["remedy"] for i,r in enumerate(state["diagnostic_results"]) if not r["correct"]]
            from .planner import enabled, trigger
            if enabled(state): trigger(state,"diagnostic_completed")
            else: dispatch(state, reason="起点诊断已完成，进入知识讲授", focus=focus)
        return {"correct": correct}

    if kind == "request_teaching":
        if state["phase"] not in ("guided_practice", "independent_assessment", "rule_check", "rule_remedy"):
            raise ValueError("请先完成诊断，或继续当前授课任务。")
        from .lecturer import dispatch
        dispatch(state, topic=payload.get("topic", "triangular_method"), reason="学生请求知识点讲解")
        return {"dispatched": True}

    if kind == "finish_lecture":
        from .lecturer import current_task
        task = current_task(state)
        if state["phase"] != "lecture" or task is None:
            raise ValueError("当前没有待交接的授课任务。")
        if task["status"] == "pending":
            raise ValueError("授课内容正在生成，请稍候。")
        if task.get("session") and task["session"]["segment_status"] != "completed":
            raise ValueError("请先完成各段理解检查；也可以暂存讲授，回到练习。")
        task["status"] = "completed"
        if task.get("session"):
            task["session"]["outcome"] = "formative_checks_passed"
        state["phase"] = task["return_phase"]
        state["active_teaching_task"] = None
        message(state, "收到授课交接。学生已选择继续，恢复原课堂任务；是否掌握仍以之后的作答证据判断。", agent="scheduler", kind="handoff", to_agent="assessment" if state["phase"] == "independent_assessment" else "student", task_id=task["id"])
        from .planner import trigger
        trigger(state,"teaching_completed")
        return {"lecture_completed": True}

    if kind in ("submit_teaching_check", "next_teaching_segment", "resolve_teaching_question", "pause_lecture"):
        from .lecturer import current_task
        from .tutor import configured
        from .teaching_session import submit_check, next_segment, resolve_question, pause
        task = current_task(state)
        if state["phase"] != "lecture" or not task or not task.get("session"):
            raise ValueError("当前没有分段授课会话。")
        if kind == "submit_teaching_check":
            result=submit_check(state, task, payload, configured())
            from .planner import enabled, trigger
            if task["session"]["segment_status"] == "needs_review" and enabled(state):
                pause(state,task)
                trigger(state,"teaching_stalled")
            return result
        if kind == "next_teaching_segment":
            next_segment(state, task, configured())
        elif kind == "resolve_teaching_question":
            resolve_question(task, payload.get("question_id"))
        else:
            pause(state, task)
        return {}

    if kind == "resume_lecture":
        from .teaching_session import resume
        task = next((t for t in state.get("teaching_tasks", []) if t["id"] == payload.get("task_id")), None)
        if not task or not task.get("session"):
            raise ValueError("未找到可恢复的授课任务。")
        resume(state, task)
        return {}

    if kind == "ask_question":
        text = str(payload.get("text", "")).strip()
        if not text or len(text) > 1500:
            raise ValueError("问题长度应为 1～1500 字。")
        message(state, text, "student")
        # Conservative assistance policy: all subject Q&A during exams counts as assisted.
        if state["phase"] == "independent_assessment" and not state.get("problem_done"):
            if not payload.get("accept_assistance"):
                message(state, "独立测验中的学科问答可能透露解法。若需要帮助，请点击‘获取学科帮助’，本题会转为辅导练习，之后再用新题复测。", agent="scheduler")
                return {"needs_assistance_confirmation": True}
            state["helped"] = True
        from .tutor import local_answer, configured
        answer = message(state, local_answer(text, state), agent="lecturer", kind="answer", status="pending" if configured() else "local")
        from .lecturer import current_task
        from .teaching_session import register_question, question_answered
        task = current_task(state)
        if task and task.get("session"):
            register_question(task, text, answer["id"])
            if not configured():
                question_answered(task, answer["id"])
        return {"message_id": answer["id"], "question": text, "remote": configured()}

    if kind == "request_hint":
        require_problem(state)
        state["helped"] = True
        state["hint_count"] += 1
        m = matrix(state["matrix"])
        if state["hint_count"] == 1 and not triangular(m):
            hint = "观察主对角线下方：第 2 行第 1 列、第 3 行第 1 列、第 3 行第 2 列。先选一个还不是零的位置，用另一行的倍数消去它。主元为零时考虑换行。"
        else:
            hint = next_hint(m)
        message(state, hint, agent="lecturer", kind="hint", status="local")
        return {"assisted": True}

    if kind == "submit_row_step":
        require_problem(state)
        if len(state["steps"]) >= 40:
            raise ValueError("本题操作已达 40 步，请整理思路或结束本次学习。")
        before = matrix(state["matrix"])
        expected, factor = transform(before, number(state["factor"]), payload.get("operation", {}))
        submitted = matrix(payload.get("result"))
        if submitted != expected:
            changed = next((i for i in range(3) if submitted[i] != expected[i]), 0)
            mistake(state, "arithmetic", f"第 {changed+1} 行的计算结果与所选行操作不一致。")
            message(state, f"第 {changed+1} 行需要再检查。把同一列的两个数代入所选运算，逐个计算；当前矩阵尚未改变。若不确定倍数怎么选，可以先提问。")
            return {"correct": False, "kind": "arithmetic", "row": changed}
        operation = payload["operation"]
        target, source = int(operation["target"])+1, int(operation.get("source", 0))+1
        label = f"R{target} ← R{target} + ({operation.get('multiple', '')}) R{source}" if operation["kind"] == "add" else (f"R{target} ↔ R{source}" if operation["kind"] == "swap" else f"R{target} ← ({operation['multiple']}) R{target}")
        state["matrix"], state["factor"] = strings(expected), str(factor)
        state["steps"].append({"label": label, "matrix": state["matrix"], "factor": state["factor"]})
        message(state, "这一步计算正确。" + ("现在已是上三角形，可以计算原行列式的值。" if triangular(expected) else "继续处理主对角线下方的非零元素。"))
        return {"correct": True}

    if kind == "submit_final_answer":
        require_problem(state)
        m = matrix(state["matrix"])
        if not triangular(m):
            message(state, "这节课需要展示三角化过程。请先把主对角线下方的元素消为零，再提交最终结果。")
            return {"correct": False, "kind": "method"}
        answer = number(payload.get("answer", ""))
        expected = determinant(matrix(get_problem(state["problem_id"])["matrix"]))
        if answer != expected:
            diagonal = m[0][0]*m[1][1]*m[2][2]
            relation_error = answer == diagonal and state["factor"] != "1"
            text = "你算出了当前三角形的值，还需要乘以 c，才能恢复原行列式的值。" if relation_error else "再检查三个对角线元素的乘积，以及 c 的符号和倍数。"
            mistake(state, "determinant_relation" if relation_error else "final_arithmetic", text)
            message(state, text)
            return {"correct": False}
        state["problem_done"] = True
        role = get_problem(state["problem_id"])["role"]
        independent = state["phase"] == "independent_assessment" and not state["helped"]
        state["attempts"].append({"problem_id": state["problem_id"], "title": get_problem(state["problem_id"])["title"], "answer": str(answer), "steps": state["steps"][:], "factor": state["factor"], "independent": independent, "hints": state["hint_count"]})
        observation = "独立完成新题，合法三角化且原行列式求值正确。" if independent else "在辅导阶段或获得帮助后完成，仍需独立复测。"
        state["evidence"].append({"concept": role, "observation": observation, "problem_id": state["problem_id"]})
        if independent and role not in state["passed"]:
            state["passed"].append(role)
        message(state, f"结果 {answer} 正确。" + observation + " 点击下方按钮进入下一环节。")
        from .planner import trigger
        trigger(state,"problem_completed")
        return {"correct": True}

    if kind == "continue":
        if not state.get("problem_done") or state["phase"] not in ("guided_practice", "independent_assessment"):
            raise ValueError("先完成当前题目。")
        from .planner import enabled, trigger
        if enabled(state):
            trigger(state,"student_continue")
            return {"planner_requested":True}
        state["phase"] = "independent_assessment"
        if "exam_regular" not in state["passed"]:
            start_problem(state, "exam_regular")
        elif "exam_swap" not in state["passed"]:
            start_problem(state, "exam_swap")
        else:
            state["phase"] = "rule_check"
            message(state, "两道独立题已经完成。最后用两个规则辨析问题，检查你能否说明变换与原值之间的关系。")
        return {}

    if kind == "submit_explanation":
        if state["phase"] != "rule_check":
            raise ValueError("当前不在规则辨析环节。")
        answers = payload.get("answers")
        if not isinstance(answers, list) or len(answers) != 2 or any(type(a) is not int or a not in range(3) for a in answers):
            raise ValueError("请完成两个规则辨析问题。")
        # Scenario 1: addition changes no value. Scenario 2: one swap and scale by 2 -> factor -1/2.
        correct = answers == [1, 2]
        note = str(payload.get("note", "")).strip()[:1500]
        state["explanation"] = {"correct": correct, "note": note, "note_evaluated": False, "method": "structured_rule_questions"}
        if correct:
            state["completed"] = True
            state["phase"] = "report"
            message(state, "本次达标：你独立完成了普通题与换行题，并通过了规则辨析。自己的文字说明已保存在笔记中，未被自动判作证明正确。")
        else:
            state["helped"] = True
            state["phase"] = "rule_remedy"
            mistake(state, "rule", "规则辨析仍有误：倍加不变；换行再乘一行以 2 后，原值是当前值的 −1/2。")
            message(state, "补充一下：倍加不改变值；交换一次行使值变号，再将一行乘 2，当前值就等于原值的 −2 倍，因此原值 = −1/2 × 当前值。这次规则辨析未通过，报告会如实记录。")
        return {"correct": correct}

    if kind == "finish":
        if state["phase"] == "report":
            return {}
        state["phase"] = "report"
        from .lecturer import current_task
        task = current_task(state)
        if task and task["status"] != "completed":
            task["status"] = "cancelled"
            state["active_teaching_task"] = None
        for item in state["messages"]:
            if item.get("status") == "pending":
                item["status"] = "local"
        state["completed"] = False
        if state.get("planner"):
            p=state["planner"]
            p["status"]="closed"
            if p.get("job") and p["job"]["status"]=="pending": p["job"]["status"]="cancelled"
        message(state, "已保存本次学习。未完成的达标项会在报告中标记，之后可开始新一轮。")
        return {}

    raise ValueError("不支持的课堂事件。")
